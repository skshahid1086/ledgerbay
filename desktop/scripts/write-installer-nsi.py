#!/usr/bin/env python3
import os, sys
from pathlib import Path
root = Path(sys.argv[1])
name = os.environ["PRODUCT"]
ver = os.environ["VERSION"]
exe = f"{name}.exe"
reg = name
nsis = f'''# Auto-generated by scripts/build-all.sh — per-user NSIS (system makensis)
Unicode true
CRCCheck on
SetCompressor /SOLID lzma
SetCompressorDictSize 64

!define PRODUCT_NAME "{name}"
!define PRODUCT_VERSION "{ver}"
!define PRODUCT_PUBLISHER "Sk Sahid"
!define PRODUCT_EXE "{exe}"
!define PRODUCT_DIR_REGKEY "Software\\{reg}"
!define UNINSTALL_REGKEY "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\{reg}"

Name "${{PRODUCT_NAME}}"
OutFile "..\\dist\\{name}-Setup-{ver}.exe"
InstallDir "$LOCALAPPDATA\\Programs\\{name}"
RequestExecutionLevel user
ShowInstDetails show
ShowUnInstDetails show
BrandingText "{name} {ver}"

!include "MUI2.nsh"
!include "FileFunc.nsh"
!include "LogicLib.nsh"

!define MUI_ABORTWARNING
!define MUI_ICON "icon.ico"
!define MUI_UNICON "icon.ico"

!insertmacro MUI_PAGE_WELCOME
!insertmacro MUI_PAGE_DIRECTORY
!insertmacro MUI_PAGE_INSTFILES
!insertmacro MUI_PAGE_FINISH
!insertmacro MUI_UNPAGE_CONFIRM
!insertmacro MUI_UNPAGE_INSTFILES
!insertmacro MUI_LANGUAGE "English"

VIProductVersion "{ver}.0"
VIAddVersionKey /LANG=1033 "ProductName" "${{PRODUCT_NAME}}"
VIAddVersionKey /LANG=1033 "ProductVersion" "${{PRODUCT_VERSION}}"
VIAddVersionKey /LANG=1033 "CompanyName" "${{PRODUCT_PUBLISHER}}"
VIAddVersionKey /LANG=1033 "FileDescription" "{name} offline GST billing"
VIAddVersionKey /LANG=1033 "FileVersion" "${{PRODUCT_VERSION}}"
VIAddVersionKey /LANG=1033 "LegalCopyright" "Copyright (c) 2026 Sk Sahid"

Section "Install" SecInstall
  SetOutPath "$INSTDIR"
  RMDir /r "$INSTDIR"
  SetOutPath "$INSTDIR"
  File /r "..\\dist\\win-unpacked\\*.*"
  CreateDirectory "$SMPROGRAMS\\{name}"
  CreateShortCut "$SMPROGRAMS\\{name}\\{name}.lnk" "$INSTDIR\\${{PRODUCT_EXE}}" "" "$INSTDIR\\${{PRODUCT_EXE}}" 0
  CreateShortCut "$DESKTOP\\{name}.lnk" "$INSTDIR\\${{PRODUCT_EXE}}" "" "$INSTDIR\\${{PRODUCT_EXE}}" 0
  CreateShortCut "$SMPROGRAMS\\{name}\\Uninstall {name}.lnk" "$INSTDIR\\Uninstall.exe"
  WriteUninstaller "$INSTDIR\\Uninstall.exe"
  WriteRegStr HKCU "${{PRODUCT_DIR_REGKEY}}" "InstallDir" "$INSTDIR"
  WriteRegStr HKCU "${{UNINSTALL_REGKEY}}" "DisplayName" "${{PRODUCT_NAME}}"
  WriteRegStr HKCU "${{UNINSTALL_REGKEY}}" "DisplayVersion" "${{PRODUCT_VERSION}}"
  WriteRegStr HKCU "${{UNINSTALL_REGKEY}}" "Publisher" "${{PRODUCT_PUBLISHER}}"
  WriteRegStr HKCU "${{UNINSTALL_REGKEY}}" "DisplayIcon" "$INSTDIR\\${{PRODUCT_EXE}}"
  WriteRegStr HKCU "${{UNINSTALL_REGKEY}}" "UninstallString" "$INSTDIR\\Uninstall.exe"
  WriteRegStr HKCU "${{UNINSTALL_REGKEY}}" "InstallLocation" "$INSTDIR"
  WriteRegDWORD HKCU "${{UNINSTALL_REGKEY}}" "NoModify" 1
  WriteRegDWORD HKCU "${{UNINSTALL_REGKEY}}" "NoRepair" 1
  ${{GetSize}} "$INSTDIR" "/S=0K" $0 $1 $2
  IntFmt $0 "0x%08X" $0
  WriteRegDWORD HKCU "${{UNINSTALL_REGKEY}}" "EstimatedSize" "$0"
SectionEnd

Section "Uninstall"
  Delete "$DESKTOP\\{name}.lnk"
  RMDir /r "$SMPROGRAMS\\{name}"
  RMDir /r "$INSTDIR"
  DeleteRegKey HKCU "${{UNINSTALL_REGKEY}}"
  DeleteRegKey HKCU "${{PRODUCT_DIR_REGKEY}}"
SectionEnd
'''
(root / "build" / "installer.nsi").write_text(nsis)
print("installer.nsi written")
